export interface SampleRecipeDetail {
  title: string;
  description: string;
  category: string;
  servings: number;
  prepTime: number;
  cookTime: number;
  difficulty: 'Easy' | 'Medium' | 'Hard';
  ingredients: { name: string; quantity: string; unit: string; orderIndex: number }[];
  steps: { stepNumber: number; title: string; description: string; timerMinutes: null }[];
}

function dish(
  title: string,
  description: string,
  category: string,
  servings: number,
  prepTime: number,
  cookTime: number,
  difficulty: SampleRecipeDetail['difficulty'],
  ingredientList: string,
  steps: [string, string][],
): SampleRecipeDetail {
  const ingredients = ingredientList.split(';').map((entry, orderIndex) => {
    const [name, quantity, unit] = entry.split('|').map((part) => part.trim());
    if (!name || !quantity || !unit) throw new Error(`Nguyên liệu không hợp lệ trong ${title}: ${entry}`);
    return { name, quantity, unit, orderIndex };
  });
  return {
    title, description, category, servings, prepTime, cookTime, difficulty, ingredients,
    steps: steps.map(([stepTitle, stepDescription], index) => ({
      stepNumber: index + 1, title: stepTitle, description: stepDescription, timerMinutes: null,
    })),
  };
}

